"""Colour theme: light (the default), dark, or "system" (follow the device, live).

The theme is rendered on ``<html data-theme="…">`` by the server, so a page never
flashes the wrong colours; static/src/app.css holds both palettes (the dark one is
generated by scripts/theme_css.py).

Where the choice is kept, and which one a page uses:

- Office pages (``templates/base.html``): a signed-in user's ``User.theme`` (it follows
  them to any computer); signed out (the sign-in pages), the ``pw_theme`` cookie; else
  light.
- Worker portal (``templates/portal/base.html``): the cookie only. Workers are not users,
  and the portal must not pick up an office account that happens to be signed in on
  the same browser.

The switch (``templates/components/theme_switch.html``) posts to ``core:set_theme``.
"""

from __future__ import annotations

import datetime

from django.conf import settings
from django.http import HttpRequest, HttpResponse
from django.utils.functional import cached_property

from .choices import Theme

COOKIE_NAME = "pw_theme"
COOKIE_MAX_AGE = int(datetime.timedelta(days=365).total_seconds())
DEFAULT = Theme.LIGHT.value


def is_valid(value: object) -> bool:
    return value in Theme.values


def device_theme(request: HttpRequest) -> str:
    """The theme kept on this browser (cookie), or light."""
    value = request.COOKIES.get(COOKIE_NAME)
    return value if is_valid(value) else DEFAULT


def office_theme(request: HttpRequest) -> str:
    """Signed-in user's theme, else this browser's, else light."""
    user = getattr(request, "user", None)
    if user is not None and user.is_authenticated:
        value = getattr(user, "theme", "")
        return value if is_valid(value) else DEFAULT
    return device_theme(request)


def set_cookie(response: HttpResponse, value: str) -> None:
    response.set_cookie(
        COOKIE_NAME,
        value,
        max_age=COOKIE_MAX_AGE,
        samesite="Lax",
        secure=settings.SESSION_COOKIE_SECURE,
        httponly=True,
    )


class RequestTheme:
    """``theme`` in templates: ``theme.office`` and ``theme.device``, worked out only when
    a template reads them (``theme.office`` may load the signed-in user)."""

    def __init__(self, request: HttpRequest):
        self._request = request

    @cached_property
    def office(self) -> str:
        return office_theme(self._request)

    @cached_property
    def device(self) -> str:
        return device_theme(self._request)
