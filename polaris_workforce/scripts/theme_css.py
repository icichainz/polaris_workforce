_THEME_BLOCK = re.compile(r"@theme\s*\{(?P<body>.*?)\n\}", re.S)
_COLOR = re.compile(r"--color-(?P<name>[a-z0-9-]+):\s*(?P<value>#[0-9a-fA-F]{6})\s*;")


def light_palette(css: str) -> dict[str, str]:
    """The colour tokens of the ``@theme`` block: {name: "#rrggbb"}."""
    match = _THEME_BLOCK.search(css)
    if match is None:
        raise ValueError("no @theme block in app.css")
    return {m["name"]: m["value"].lower() for m in _COLOR.finditer(match["body"])}


def _declarations(palette: dict[str, str], indent: str) -> str:
    return "\n".join(f"{indent}--color-{name}: {value};" for name, value in palette.items())


def generated(css: str) -> str:
    light = light_palette(css)
    missing = sorted(set(light) - set(DARK))
    extra = sorted(set(DARK) - set(light))
    if missing or extra:
        raise ValueError(f"DARK out of step with @theme: missing {missing}, unknown {extra}")
    dark = {name: DARK[name] for name in light}
    return "\n".join(
        [
            BEGIN,
            "",
            "/*",
            " * Light is the default. Native controls (date pickers, selects, scrollbars)",
            " * follow color-scheme. The selectors are not tied to :root, so a block of a",
            ' * page can preview the other theme (data-theme="dark" on a div: /_components/).',
            " */",
            ":root,",
            '[data-theme="light"] {',
            "  color-scheme: light;",
            "}",
            "",
            '[data-theme="light"] {',
            _declarations(light, "  "),
            "}",
            "",
            '[data-theme="system"] {',
            "  color-scheme: light dark;",
            "}",
            "",
            '[data-theme="dark"] {',
            "  color-scheme: dark;",
            _declarations(dark, "  "),
            "}",
            "",
            "@media (prefers-color-scheme: dark) {",
            '  [data-theme="system"] {',
            "    color-scheme: dark;",
            _declarations(dark, "    "),
            "  }",
            "}",
            "",
            "/* Paper is white: print the light theme whatever the screen shows. */",
            "@media print {",
            "  [data-theme] {",
            "    color-scheme: light;",
            _declarations(light, "    "),
            "  }",
            "}",
            "",
            END,
        ]
    )


def updated(css: str) -> str:
    section = generated(css)
    if BEGIN in css:
        head, rest = css.split(BEGIN, 1)
        _, tail = rest.split(END, 1)
        return f"{head}{section}{tail}"
    return f"{css.rstrip()}\n\n{section}\n"


def main(argv: list[str]) -> int:
    css = APP_CSS.read_text(encoding="utf-8")
    new = updated(css)
    if "--check" in argv:
        if new != css:
            print("static/src/app.css is out of date: run scripts/theme_css.py", file=sys.stderr)
            return 1
        return 0
    if new != css:
        APP_CSS.write_text(new, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
